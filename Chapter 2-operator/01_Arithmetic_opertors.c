// To perform operations on two numbers
#include <stdio.h>
int main()
{
   int a = 6.0;
   int b = 7.0;
   int c;
    printf("The value of a is %d, value of b is %d and sum is %d\n", a, b, c = a + b);
    printf("The value of a is %d, value of b is %d and difference is %d\n", a, b, c = a - b);
    printf("The value of a is %d, value of b is %d and average is %f\n", a, b, c = (a + b) / 2);
    return 0;
}